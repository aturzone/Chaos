def knurl(n=48, y=48, h=34, w=7.0):
    """A ring of rounded ridges. Two rings, offset, read as a real knurl."""
    out = [f'  <g id="knurl">\n'
           f'    <rect x="{256 - w/2:.2f}" y="{y}" width="{w}" height="{h}" '
           f'rx="{w/2:.2f}" fill="url(#ridge)"/>\n  </g>\n']
    step = 360.0 / n
    for i in range(1, n):
        out.append(f'  <use href="#knurl" transform="rotate({i*step:.4g} 256 256)"/>\n')
    return ''.join(out)


