def logo_group(cx, cy, diameter, clip_id):
    s = diameter / max(LOGO_W, LOGO_H)
    tx = cx - (LOGO_W * s) / 2
    ty = cy - (LOGO_H * s) / 2
    return (
        f'  <g clip-path="url(#{clip_id})">\n'
        f'    <g transform="translate({tx:.3f},{ty:.3f}) scale({s:.6f})">\n'
        f'{inner}\n'
        f'    </g>\n'
        f'  </g>\n'
    )


