# --- the plate ---------------------------------------------------------------
# Four detents. 12 o'clock is CORE, and the others sit at 90 degree steps, so
# the pointer's angle IS the mode and nothing has to be looked up.
MODES = [
    (0,   'CORE',   'holds the models, answers others'),
    (90,  'CLIENT', 'uses a CORE elsewhere'),
    (180, 'HELPER', 'lends memory and cores'),
    (270, 'ALONE',  'only this machine'),
]

import math

ticks, labels = [], []
for ang, name, _ in MODES:
    a = math.radians(ang - 90)
    for r0, r1, wdt, col in ((250, 274, 5, '#3a3a38'), (278, 288, 3, '#8a8a86')):
        x0, y0 = 320 + r0 * math.cos(a), 320 + r0 * math.sin(a)
        x1, y1 = 320 + r1 * math.cos(a), 320 + r1 * math.sin(a)
        ticks.append(f'  <line x1="{x0:.2f}" y1="{y0:.2f}" x2="{x1:.2f}" y2="{y1:.2f}" '
                     f'stroke="{col}" stroke-width="{wdt}" stroke-linecap="round"/>\n')
    lx, ly = 320 + 302 * math.cos(a), 320 + 302 * math.sin(a)
    anchor = 'middle'
    dy = '0.36em'
    if ang == 90:
        anchor, dy = 'start', '0.36em'
    elif ang == 270:
        anchor, dy = 'end', '0.36em'
    elif ang == 180:
        dy = '0.95em'
    else:
        dy = '-0.35em'
    labels.append(f'  <text x="{lx:.1f}" y="{ly:.1f}" text-anchor="{anchor}" dy="{dy}" '
                  f'font-family="Segoe UI, Inter, system-ui, sans-serif" font-size="26" '
                  f'font-weight="600" letter-spacing="2.5" fill="#2c2c2a">{name}</text>\n')

